class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) => AppStrings.supportedLocales.any(
        (Locale supported) => supported.languageCode == locale.languageCode,
      );

  @override
  Future<AppStrings> load(Locale locale) async => AppStrings(locale);

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppStrings> old) => false;
}

extension AppStringsContext on BuildContext {
  /// Translate [key] using the closest [AppStrings] localisation.
  String tr(String key) => AppStrings.of(this).t(key);

  String trp(String key, Map<String, Object> values) => AppStrings.of(this).tp(key, values);

  bool get isRtl => AppStrings.of(this).isRtl;
}
