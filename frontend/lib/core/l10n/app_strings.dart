  static AppStrings of(BuildContext context) {
    final AppStrings? strings = Localizations.of<AppStrings>(context, AppStrings);
    assert(strings != null, 'AppStrings is missing from the widget tree');
    return strings ?? const AppStrings(Locale('en'));
  }

  bool get isRtl => locale.languageCode == 'ar';

  TextDirection get direction => isRtl ? TextDirection.rtl : TextDirection.ltr;

  /// Translate [key]; unknown keys surface the key itself so a missing
  /// translation is obvious during review instead of silently blank.
  String t(String key) {
    final Map<String, String> language = _values[locale.languageCode] ?? _en;
    return language[key] ?? _en[key] ?? key;
  }

  /// Translate with `{placeholder}` substitution.
  String tp(String key, Map<String, Object> values) {
    String text = t(key);
    values.forEach((String name, Object value) {
      text = text.replaceAll('{$name}', '$value');
    });
    return text;
  }

  static Map<String, String> valuesFor(String languageCode) => _values[languageCode] ?? _en;

